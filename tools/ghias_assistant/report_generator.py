#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""
GHIAS Assistant
Professional Daily Report Generator
Version: 0.9.3
"""

from datetime import datetime
from pathlib import Path


PROJECT_ROOT = Path(__file__).resolve().parents[2]



def get_report_folder():

    now = datetime.now()

    folder = (
        PROJECT_ROOT
        / "docs"
        / "DAILY_REPORTS"
        / "AUTO"
        / str(now.year)
        / f"{now.month:02d}"
    )

    folder.mkdir(
        parents=True,
        exist_ok=True
    )

    return folder



def create_report(work_description, project_info=None):

    now = datetime.now()

    report_folder = get_report_folder()

    report_file = (
        report_folder /
        f"{now.strftime('%Y-%m-%d')}.md"
    )


    content = f"""# GHIAS Daily Report

## Date

{now.strftime('%Y-%m-%d')}


## Time

{now.strftime('%H:%M:%S')}


## Project

GHIAS


"""


    if project_info:

        content += f"""## Path

{project_info.get('path','')}


## Branch

{project_info.get('branch','')}


## Last Commit

{project_info.get('last_commit','')}


"""


    content += f"""## Work Description

{work_description}


## Generated By

GHIAS Assistant v0.9.3

"""


    report_file.write_text(
        content,
        encoding="utf-8"
    )


    return report_file



if __name__ == "__main__":

    print(
        "GHIAS Daily Report Generator v0.9.3"
    )


    work = input(
        "\nWhat did you do today?\n> "
    )


    report = create_report(
        work
    )


    print()

    print(
        "Report created:"
    )

    print(report)